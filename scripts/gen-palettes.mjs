// Generates src/theme/palettes.css and src/theme/palettes.ts from src/theme/palettes.json.
import { readFileSync, writeFileSync } from "node:fs";

const palettes = JSON.parse(readFileSync("src/theme/palettes.json", "utf8"));
const keys = [
  "ground", "surface", "surface2", "surface3", "line", "lineStrong",
  "ink", "ink2", "ink3", "accent", "accentInk", "accentSoft", "focus",
  "ok", "okSoft", "warn", "warnSoft", "risk", "riskSoft", "info", "infoSoft",
  "person", "highlight", "highlightInk",
];

let css = "/* Generated by scripts/gen-palettes.mjs from palettes.json. Do not edit. */\n";
for (const [id, p] of Object.entries(palettes)) {
  const sel = id === "graphite" ? `:root, html[data-palette="graphite"]` : `html[data-palette="${id}"]`;
  const lines = keys.map((k) => `  --${k}: ${p[k]};`);
  p.agents.forEach((c, i) => lines.push(`  --agent-${i + 1}: ${c};`));
  lines.push(`  color-scheme: ${p.mode};`);
  css += `${sel} {\n${lines.join("\n")}\n}\n`;
}
writeFileSync("src/theme/palettes.css", css);

const meta = Object.entries(palettes).map(([id, p]) => ({
  id,
  name: p.name,
  mode: p.mode,
  about: p.about,
  swatch: [p.ground, p.surface2, p.ink, p.accent, p.ok, p.risk],
  dots: [p.ground, p.accent, p.ok, p.risk],
}));
writeFileSync(
  "src/theme/palettes.ts",
  "// Generated by scripts/gen-palettes.mjs. Do not edit.\n" +
    "export const PALETTES = " + JSON.stringify(meta, null, 2) + " as const;\n\n" +
    "export type PaletteId = (typeof PALETTES)[number][\"id\"];\n",
);
console.log("palettes:", Object.keys(palettes).join(", "));
