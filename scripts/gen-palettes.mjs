// Generates src/theme/palettes.css and src/theme/palettes.ts from src/theme/palettes_v2.json:
// three palettes, each with a light and a dark token set.
import { readFileSync, writeFileSync } from "node:fs";

const palettes = JSON.parse(readFileSync("src/theme/palettes_v2.json", "utf8"));
const keys = Object.keys(palettes.graphite.light);

let css = "/* Generated by scripts/gen-palettes.mjs from palettes_v2.json. Do not edit. */\n";
for (const [id, p] of Object.entries(palettes)) {
  for (const mode of ["light", "dark"]) {
    const t = p[mode];
    const sel =
      id === "graphite" && mode === "light"
        ? `:root, html[data-palette="graphite"][data-mode="light"]`
        : `html[data-palette="${id}"][data-mode="${mode}"]`;
    const lines = keys.map((k) => `  --${k}: ${t[k]};`);
    // agents and people keep a neutral hue family per theme
    lines.push(`  --person: ${t.ink};`);
    lines.push(`  color-scheme: ${mode};`);
    css += `${sel} {\n${lines.join("\n")}\n}\n`;
  }
}
writeFileSync("src/theme/palettes.css", css);

const meta = Object.entries(palettes).map(([id, p]) => ({
  id,
  name: p.name,
  about: p.about,
  swatch: {
    light: [p.light.ground, p.light.surface2, p.light.ink, p.light.accent, p.light.vizOk, p.light.vizRisk, p.light.highlight],
    dark: [p.dark.ground, p.dark.surface2, p.dark.ink, p.dark.accent, p.dark.vizOk, p.dark.vizRisk, p.dark.highlight],
  },
  dots: { light: [p.light.ground, p.light.accent, p.light.vizOk, p.light.vizRisk], dark: [p.dark.ground, p.dark.accent, p.dark.vizOk, p.dark.vizRisk] },
}));
writeFileSync(
  "src/theme/palettes.ts",
  "// Generated by scripts/gen-palettes.mjs. Do not edit.\n" +
    "export const PALETTES = " + JSON.stringify(meta, null, 2) + " as const;\n\n" +
    "export type PaletteId = (typeof PALETTES)[number][\"id\"];\n" +
    "export type Mode = \"light\" | \"dark\";\n",
);
console.log("palettes:", Object.keys(palettes).join(", "), "× light, dark");
